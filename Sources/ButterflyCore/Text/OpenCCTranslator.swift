    /// Convert text to Traditional Chinese (Taiwan standard terms + glyphs), preserving English and symbols
    public func convert(_ text: String) -> String {
        guard !text.isEmpty else { return text }
        
        var result = text
        
        // 1. Phrase-level vocabulary replacement (longest phrase match first)
        let sortedPhrases = taiwanPhraseMap.keys.sorted { $0.count > $1.count }
        for phrase in sortedPhrases {
            if let replacement = taiwanPhraseMap[phrase], result.contains(phrase) {
                result = result.replacingOccurrences(of: phrase, with: replacement)
            }
        }
        
        // 2. System Cocoa Hans-to-Hant transform
        if let transformed = result.applyingTransform(StringTransform("Hans-Hant"), reverse: false) {
            result = transformed
        }
        
        // 3. Fallback character dictionary replacement
        var finalChars = [Character]()
        for char in result {
            if let traditional = charMap[char] {
                finalChars.append(traditional)
            } else {
                finalChars.append(char)
            }
        }
        
        return String(finalChars)
    }
    
    /// Check if text contains any remaining Simplified Chinese characters (for test assertions)
    public func containsSimplified(_ text: String) -> Bool {
        for char in text {
            if let trad = charMap[char], trad != char {
                return true
            }
        }
        return false
    }
